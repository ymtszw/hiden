<#
.SYNOPSIS
    Deploy agent-dotfiles to Antigravity, Claude Code, OpenAI Codex, and GitHub Copilot on Windows.
.DESCRIPTION
    Builds consolidated rules (00-core + 10-windows + optional local.md) and deploys skills
    from common, windows, and local categories via directory junctions.
.PARAMETER Adopt
    Detect unlinked/unmanaged skill directories in agent folders and adopt them into skills/local/.
#>

[CmdletBinding()]
param(
    [switch]$Adopt
)

$ErrorActionPreference = "Stop"
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$BuildDir = Join-Path $ScriptDir "build"
$UserProfile = [System.Environment]::GetFolderPath([System.Environment+SpecialFolder]::UserProfile)

Write-Host "==> [agents] Setting up agent configurations for Windows..." -ForegroundColor Cyan

# 1. Build consolidated rules
if (-not (Test-Path $BuildDir)) {
    New-Item -ItemType Directory -Path $BuildDir -Force | Out-Null
}

$CoreRule = Join-Path $ScriptDir "rules\00-core.md"
$WinRule = Join-Path $ScriptDir "rules\10-windows.md"
$LocalRule1 = Join-Path $ScriptDir "AGENTS.local.md"
$LocalRule2 = Join-Path $ScriptDir "rules\local.md"
$DestRuleFile = Join-Path $BuildDir "AGENTS.md"

$RuleContent = @(
    "<!-- Generated by agent-dotfiles. Do not edit directly; edit agents/rules/*.md or local.md -->"
)
if (Test-Path $CoreRule) { $RuleContent += (Get-Content -Raw $CoreRule) }
if (Test-Path $WinRule) { $RuleContent += (Get-Content -Raw $WinRule) }
if (Test-Path $LocalRule1) {
    Write-Host "==> [agents] Merging local override: AGENTS.local.md" -ForegroundColor Yellow
    $RuleContent += (Get-Content -Raw $LocalRule1)
} elseif (Test-Path $LocalRule2) {
    Write-Host "==> [agents] Merging local override: rules/local.md" -ForegroundColor Yellow
    $RuleContent += (Get-Content -Raw $LocalRule2)
}

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($DestRuleFile, ($RuleContent -join "`r`n`r`n"), $utf8NoBom)

# Safe Junction / Symlink Helper
function Link-DirectorySafe {
    param(
        [string]$Target,
        [string]$Link
    )
    if (Test-Path $Link) {
        $item = Get-Item $Link -Force -ErrorAction SilentlyContinue
        if ($item.Attributes -match "ReparsePoint") {
            # Check if it already points to the correct target
            if ($item.Target -eq $Target -or $item.Target -eq "$Target\") {
                return
            }
            $item.Delete()
        } else {
            # Existing real directory - avoid destructive wipeout
            $backupPath = "$Link.bak-$((Get-Date).ToString('yyyyMMdd-HHmmss'))"
            Write-Warning "Existing directory at '$Link' is not a link. Renaming to '$backupPath' to avoid data loss."
            Move-Item -Path $Link -Destination $backupPath -Force
        }
    }
    try {
        New-Item -ItemType SymbolicLink -Path $Link -Target $Target -ErrorAction Stop | Out-Null
    } catch {
        # Fallback to Directory Junction (standard on Windows for unprivileged users)
        New-Item -ItemType Junction -Path $Link -Target $Target -ErrorAction Stop | Out-Null
    }
}

# 2. Deploy rules across agents
$AgyDir = Join-Path $UserProfile ".gemini\config"
$ClaudeDir = Join-Path $UserProfile ".claude"
$CodexDir = Join-Path $UserProfile ".codex"
$CopilotDir = Join-Path $UserProfile ".copilot"

# Antigravity (AGY)
if (Test-Path $AgyDir) {
    Copy-Item -Path $DestRuleFile -Destination (Join-Path $AgyDir "AGENTS.md") -Force
    Write-Host "  ✓ Deployed rules to ~/.gemini/config/AGENTS.md" -ForegroundColor Green
}

# Claude Code
New-Item -ItemType Directory -Path $ClaudeDir -Force | Out-Null
Copy-Item -Path $DestRuleFile -Destination (Join-Path $ClaudeDir "CLAUDE.md") -Force
Write-Host "  ✓ Deployed rules to ~/.claude/CLAUDE.md" -ForegroundColor Green

# OpenAI Codex
New-Item -ItemType Directory -Path $CodexDir -Force | Out-Null
Copy-Item -Path $DestRuleFile -Destination (Join-Path $CodexDir "AGENTS.md") -Force
Write-Host "  ✓ Deployed rules to ~/.codex/AGENTS.md" -ForegroundColor Green

# GitHub Copilot
New-Item -ItemType Directory -Path $CopilotDir -Force | Out-Null
Copy-Item -Path $DestRuleFile -Destination (Join-Path $CopilotDir "copilot-instructions.md") -Force
Write-Host "  ✓ Deployed rules to ~/.copilot/copilot-instructions.md" -ForegroundColor Green

# 3. Optional Adopt: Ingest unmanaged skill directories into skills/local/
$LocalSkillsDir = Join-Path $ScriptDir "skills\local"
if (-not (Test-Path $LocalSkillsDir)) {
    New-Item -ItemType Directory -Path $LocalSkillsDir -Force | Out-Null
}

if ($Adopt) {
    Write-Host "==> [agents] Scanning for unmanaged skills to adopt into skills/local/..." -ForegroundColor Yellow
    $CandidateSkillsDirs = @()
    if (Test-Path $AgyDir) { $CandidateSkillsDirs += (Join-Path $AgyDir "skills") }
    $CandidateSkillsDirs += (Join-Path $ClaudeDir "skills")

    foreach ($scanDir in $CandidateSkillsDirs) {
        if (Test-Path $scanDir) {
            Get-ChildItem -Directory -Path $scanDir | ForEach-Object {
                if (-not ($_.Attributes -match "ReparsePoint")) {
                    $skillName = $_.Name
                    $targetLocal = Join-Path $LocalSkillsDir $skillName
                    if (-not (Test-Path $targetLocal)) {
                        Write-Host "  -> Adopting unmanaged skill '$skillName' from $scanDir..." -ForegroundColor Cyan
                        Move-Item -Path $_.FullName -Destination $targetLocal -Force
                    }
                }
            }
        }
    }
}

# 4. Deploy skills (common, windows, local)
function Deploy-Skills {
    param([string]$DestSkillsDir)
    New-Item -ItemType Directory -Path $DestSkillsDir -Force | Out-Null

    $count = 0
    foreach ($cat in @("common", "windows", "local")) {
        $CatDir = Join-Path $ScriptDir "skills\$cat"
        if (Test-Path $CatDir) {
            Get-ChildItem -Directory -Path $CatDir | ForEach-Object {
                $targetSkill = $_.FullName
                $linkSkill = Join-Path $DestSkillsDir $_.Name
                Link-DirectorySafe -Target $targetSkill -Link $linkSkill
                $count++
            }
        }
    }
    return $count
}

if (Test-Path $AgyDir) {
    $c = Deploy-Skills -DestSkillsDir (Join-Path $AgyDir "skills")
    Write-Host "  ✓ Deployed $c skills to ~/.gemini/config/skills/ (junctions)" -ForegroundColor Green
    # Clean up legacy skills.json if present to prevent duplicate scans
    $legacyJson = Join-Path $AgyDir "skills.json"
    if (Test-Path $legacyJson) {
        Remove-Item -Path $legacyJson -Force -ErrorAction SilentlyContinue
    }
}

$c = Deploy-Skills -DestSkillsDir (Join-Path $ClaudeDir "skills")
Write-Host "  ✓ Deployed $c skills to ~/.claude/skills/ (junctions)" -ForegroundColor Green

$c = Deploy-Skills -DestSkillsDir (Join-Path $CodexDir "skills")
Write-Host "  ✓ Deployed $c skills to ~/.codex/skills/ (junctions)" -ForegroundColor Green

$c = Deploy-Skills -DestSkillsDir (Join-Path $CopilotDir "skills")
Write-Host "  ✓ Deployed $c skills to ~/.copilot/skills/ (junctions)" -ForegroundColor Green

Write-Host "==> [agents] Windows deployment completed successfully!" -ForegroundColor Cyan
